"""
Render benchmark/v3/REVIEW.md: every new query and every new gold label, with
the exact text each span covers, so the labels can be reviewed before the
query set is frozen.

    python -m benchmark.v3.review [--archive PATH]

Generated, never hand-edited: regenerate after any change to queries.yaml.
"""

from __future__ import annotations

import argparse
import os
import sys
from collections import Counter

V3_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(os.path.dirname(V3_DIR))
if PROJECT_ROOT not in sys.path:
    sys.path.insert(0, PROJECT_ROOT)

from benchmark.v3 import dataset as D
from benchmark.v3 import gold as G

REVIEW_PATH = os.path.join(V3_DIR, "REVIEW.md")
EXCERPT = 360
QTYPE_ORDER = ("exact_identifier", "misspelled", "keyword", "paraphrase", "multi_hop",
               "list_all", "repo_identity", "unanswerable")


def _excerpt(text: str, limit: int = EXCERPT) -> str:
    text = text.strip("\n")
    if len(text) > limit:
        text = text[:limit].rstrip() + " …"
    return text.replace("```", "ˋˋˋ")


def _where(parents: dict, span: G.Span) -> str:
    text = parents[(span.file, span.page)]
    line = text.count("\n", 0, span.start) + 1
    page = f" p{span.page}" if span.file.endswith(".pdf") else ""
    return f"`{span.file}`{page} line {line}, chars [{span.start}, {span.end})"


def _chunk_label(chunks: list, i: int) -> str:
    c = chunks[i]
    return f"{G.chunk_file(c)}@{c.metadata.get('start_index')}"


def render_query(q: dict, r: D.Resolved, parents: dict, chunks: list, near) -> list[str]:
    out = [f"#### `{q['id']}` — {q['question']}", ""]
    out.append(f"- category `{q['category']}` · qtype `{q['qtype']}` · domain `{q['domain']}`")
    if q["qtype"] == "unanswerable":
        out.append(f"- **unanswerable** — {q['notes'].strip()}")
        out.append("")
        return out
    out.append(f"- gold: {len(r.spans)} span(s), {r.n_parts} part(s), "
               f"{len(r.direct)} chunk(s) overlap directly; "
               f"question/gold token overlap {r.overlap:.2f}")
    extra = sorted(set(r.expanded) - set(r.direct))
    if extra:
        labels = ", ".join(f"`{_chunk_label(chunks, i)}`" for i in extra[:6])
        more = f" (+{len(extra) - 6} more)" if len(extra) > 6 else ""
        out.append(f"- near-duplicates also counted as gold: {labels}{more}")
    out.append(f"- notes: {q['notes'].strip()}")
    out.append("")
    for n, s in enumerate(r.spans, 1):
        ev = f" · evidence `{s.evidence}` ✓ found in span" if s.evidence else " · (v2 range, no evidence string)"
        out.append(f"{n}. part `{'/'.join(s.parts)}` · {_where(parents, s)}{ev}")
        out.append("")
        out.append("   ```text")
        for line in _excerpt(G.parent_slice(parents, s)).splitlines():
            out.append("   " + line)
        out.append("   ```")
    out.append("")
    return out


def render(data: dict, resolved: dict, parents: dict, chunks: list, near,
           errors: list, warnings: list, near_mode: str) -> str:
    queries = data["queries"]
    new = [q for q in queries if q["origin"] == "v3"]
    old = [q for q in queries if q["origin"] == "v2"]
    lines = ["# v3 query set — labels for review", "",
             "Generated by `python -m benchmark.v3.review` from `benchmark/v3/queries.yaml`.",
             "Do not edit by hand. **Nothing is frozen yet**: the dev/holdout split and its",
             "SHA-256 manifest are written only after this review.", ""]

    lines += ["## Summary", ""]
    n_ans = len(D.answerable(queries))
    lines += [
        f"- {len(queries)} queries: {n_ans} answerable, {len(queries) - n_ans} unanswerable.",
        f"- {len(old)} carried over from v2 (wording unchanged), {len(new)} new.",
        (f"- Validation: {len(errors)} error(s). Every gold span was located in the real corpus "
         "text and every `evidence` string was found inside its span."),
        f"- Near-duplicates counted as gold: {near_mode}.",
        "",
    ]
    lines += ["| domain | qtype | v2 | new | total |", "|---|---|---|---|---|"]
    counts = Counter((q["domain"], q["qtype"], q["origin"]) for q in queries)
    for dom in D.DOMAINS:
        for qt in QTYPE_ORDER:
            a, b = counts[(dom, qt, "v2")], counts[(dom, qt, "v3")]
            if a or b:
                lines.append(f"| {dom} | {qt} | {a} | {b} | {a + b} |")
    lines.append("")

    lines += ["## Points to decide in review", ""]
    lines += [
        (f"1. **Size.** {n_ans} answerable against a target of about 150. Candidates to drop if "
         "you want to trim: `msp-09` (same fact as `dfa-04`), `isw-13`, `kw-02`, `lst-10`."),
        ("2. **Parts.** Spans sharing a `part` are alternatives; different parts are separate "
         "pieces of the answer. Hit@k = any part found; Recall@20 = share of parts found."),
        "3. **v2 wording flagged by the overlap audit** (kept unchanged, as v2 did):",
    ]
    for w in warnings:
        lines.append(f"   - {w}")
    lines += [
        ("4. **v2 docx labels** keep their v2 character ranges (already span-level); they are "
         "listed at the end for completeness, not re-derived."),
        ("5. **Two v2 docx labels look too broad.** `dex-01` (Kinesics) and `dco-10` (body "
         "language) are labelled with the whole duplicated block, [62169, 67608) and [67648, "
         "73087): 15 chunks covering kinesics, the 4 Ps of presentation and visual aids. The "
         "kinesics material is [62169, 62892) and [67648, 68371). Proposed: narrow both to those "
         "ranges. Left unchanged pending your decision, because it changes v2 labels."),
        "",
    ]

    lines += ["## 1. New queries", ""]
    for dom in D.DOMAINS:
        for qt in QTYPE_ORDER:
            group = [q for q in new if q["domain"] == dom and q["qtype"] == qt]
            if not group:
                continue
            lines += [f"### {dom} · {qt} ({len(group)})", ""]
            for q in group:
                lines += render_query(q, resolved[q["id"]], parents, chunks, near)

    lines += ["## 2. New span-level gold on existing v2 queries", "",
              "These questions are unchanged; v2 labelled them at file or page level.", ""]
    for dom in D.DOMAINS:
        for qt in QTYPE_ORDER:
            group = [q for q in old if q["domain"] == dom and q["qtype"] == qt
                     and q["qtype"] != "unanswerable"
                     and any("anchor" in e for e in q.get("gold") or [])]
            if not group:
                continue
            lines += [f"### {dom} · {qt} ({len(group)})", ""]
            for q in group:
                lines += render_query(q, resolved[q["id"]], parents, chunks, near)

    lines += ["## 3. Unchanged v2 docx range labels", ""]
    for q in old:
        if q["qtype"] == "unanswerable" or any("anchor" in e for e in q.get("gold") or []):
            continue
        r = resolved[q["id"]]
        spans = "; ".join(f"[{s.start}, {s.end})" for s in r.spans)
        lines.append(f"- `{q['id']}` ({q['qtype']}) {q['question']} — {spans}, "
                     f"{len(r.direct)} chunk(s)")
    lines.append("")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--archive", help="local psf/requests tarball at the pinned commit")
    args = parser.parse_args()

    from benchmark.v3.corpus import load_corpus

    chunks, parents, _meta = load_corpus(args.archive)
    near_mode = (f"a chunk containing >= {G.CONTAINMENT_THRESHOLD:.0%} of a gold chunk's "
                 f"5-word shingles (gold chunk >= {G.MIN_GOLD_SHINGLES} shingles)")
    near = G.NearDuplicates(chunks)
    data = D.load()
    resolved, errors, warnings = D.validate(data, chunks, parents, near)
    if errors:
        for e in errors:
            print("ERROR", e)
        return 1
    with open(REVIEW_PATH, "w", encoding="utf-8") as handle:
        handle.write(render(data, resolved, parents, chunks, near, errors, warnings, near_mode))
    print(f"written: {REVIEW_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
