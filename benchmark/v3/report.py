"""
Render benchmark/v3/RESULTS.md from benchmark/v3/results.json.

    python -m benchmark.v3.report

Generated, never hand-edited, so the report cannot drift from the data.
"""

from __future__ import annotations

import json
import os
import sys

V3_DIR = os.path.dirname(os.path.abspath(__file__))
RESULTS_PATH = os.path.join(V3_DIR, "results.json")
REPORT_PATH = os.path.join(V3_DIR, "RESULTS.md")

ARMS = ("production", "production_no_pin", "dense_fallback", "dense_plain", "bm25")
SPLITS = ("dev", "holdout")
QTYPES = ("exact_identifier", "keyword", "misspelled", "paraphrase", "multi_hop",
          "list_all", "repo_identity")


def pct(m: dict | None) -> str:
    if m is None:
        return "—"
    return f"{100 * m['mean']:.1f} [{100 * m['ci_low']:.1f}, {100 * m['ci_high']:.1f}]"


def short(m: dict | None) -> str:
    return "—" if m is None else f"{100 * m['mean']:.1f}"


def diff(d: dict) -> str:
    mark = " *" if d["excludes_zero"] else ""
    return f"{100 * d['diff']:+.1f} [{100 * d['ci_low']:+.1f}, {100 * d['ci_high']:+.1f}]{mark}"


def block(r: dict, key: str) -> dict | None:
    return r["aggregates"].get(key)


def render(r: dict) -> str:
    out = ["# v3 retrieval baseline", "",
           "Generated by `python -m benchmark.v3.report` from `results.json`. Do not edit by hand.", "",
           ("This is the **before** measurement for retrieval Phases 1 and 2. It was produced once, "
           "on the frozen query set, before any retrieval change."), ""]

    fid = r.get("fidelity_default_hnsw") or {}
    out += ["## Run", "",
            (f"- Frozen query set: manifest `{(r['manifest_sha256'] or '')[:12]}`; "
            f"{r['unanswerable']['n']} unanswerable and "
            f"{sum(1 for q in r['per_query'].values() if q['qtype'] != 'unanswerable')} answerable queries."),
            (f"- Retriever under test (`production`): `build_hybrid_retriever` as shipped: "
            f"{r['config']['vector_search_type']} {r['config']['vector_search_kwargs']}, "
            f"BM25 top {r['config']['bm25_candidate_k']}, RRF k={r['config']['rrf_smoothing']}, "
            f"weights {r['config']['vector_weight']}/{r['config']['bm25_weight']}, "
            f"final_k={r['config']['final_k']}, README pin on."),
            (f"- README pin fired on {r['pin_fired_answerable']} answerable and "
            f"{r['unanswerable']['pin_fired']} of {r['unanswerable']['n']} unanswerable queries."),
            (f"- Store: exhaustive HNSW `{r['store']['hnsw']}`. Against a store with Chroma's default "
            f"HNSW (what production uses), {fid.get('identical')} of {fid.get('total')} production "
            f"top-5 lists are identical (differ: {', '.join(fid.get('differ', [])) or 'none'})."),
            (f"- Bootstrap: {r['bootstrap']['resamples']} paired resamples, seed {r['bootstrap']['seed']}, "
            "95% percentile intervals. `*` marks a paired difference whose interval excludes 0."),
            "- Libraries: " + ", ".join(f"{k} {v}" for k, v in r["libraries"].items()), ""]

    out += ["## Reading notes", "",
            "- `dense_fallback` returns 10 chunks, so its Recall@20 column is effectively Recall@10.",
            ("- The README pin only ever replaces the 5th result, so Hit@1 and ranks 1-4 are "
            "identical for `production` and `production_no_pin`; any difference is the pin's effect."),
            ("- MMR's order is discarded by LangChain's Chroma wrapper, so `dense_fallback` and "
            "`dense_plain` share their top-1 (identical Hit@1)."),
            "- Tune on **dev** only; **holdout** confirms a change once, at the end.",
            ""]
    out += ["## Headline: all answerable queries", "",
            ("Percentages with 95% bootstrap intervals. Hit@k / MRR@5 measure ranking (the 5 chunks "
            "the generator sees); Recall@20 measures the candidate pool (share of gold parts in the "
            "top 20; for `production` the same retriever with final_k=20)."), ""]
    for split in SPLITS:
        b = block(r, f"{split}/all/all")
        out += [f"### {split} (n = {b['n']})", "",
                "| arm | Hit@1 | Hit@5 | MRR@5 | Recall@20 | file-level Hit@5 (code) |",
                "|---|---|---|---|---|---|"]
        for arm in ARMS:
            a = b["arms"][arm]
            fl = a.get("file_hit@5")
            out.append(f"| `{arm}` | {pct(a['hit@1'])} | {pct(a['hit@5'])} | {pct(a['mrr@5'])} | "
                       f"{pct(a['recall@20'])} | {'—' if fl is None else f'{100 * fl:.1f}'} |")
        out += ["", "Paired difference against `production` (arm minus production, points):", "",
                "| arm | Hit@1 | Hit@5 | MRR@5 | Recall@20 |", "|---|---|---|---|---|"]
        for arm in ARMS[1:]:
            d = b["vs_production"][arm]
            out.append(f"| `{arm}` | {diff(d['hit@1'])} | {diff(d['hit@5'])} | {diff(d['mrr@5'])} | "
                       f"{diff(d['recall@20'])} |")
        out.append("")

    out += ["## By domain", ""]
    for split in SPLITS:
        out += [f"### {split}", "", "| domain | n | arm | Hit@1 | Hit@5 | MRR@5 | Recall@20 |",
                "|---|---|---|---|---|---|---|"]
        for dom in ("code", "docs"):
            b = block(r, f"{split}/{dom}/all")
            for arm in ARMS:
                a = b["arms"][arm]
                out.append(f"| {dom} | {b['n']} | `{arm}` | {pct(a['hit@1'])} | {pct(a['hit@5'])} | "
                           f"{pct(a['mrr@5'])} | {pct(a['recall@20'])} |")
        out.append("")

    out += ["## By query type (Hit@5, %)", "",
            "Small cells: read the n before the number. Intervals are in `results.json`.", ""]
    for split in SPLITS:
        out += [f"### {split}", "", "| qtype | n | " + " | ".join(f"`{a}`" for a in ARMS) + " |",
                "|---|---|" + "---|" * len(ARMS)]
        for qt in QTYPES:
            b = block(r, f"{split}/all/{qt}")
            if b:
                out.append(f"| {qt} | {b['n']} | " +
                           " | ".join(short(b["arms"][a]["hit@5"]) for a in ARMS) + " |")
        out.append("")

    out += ["## New metrics", "",
            ("**list_all: chunk coverage**: share of the chunks overlapping the gold span that are "
            "retrieved (the generator needs most of a list, not one chunk of it)."), ""]
    for split in SPLITS:
        b = block(r, f"{split}/all/list_all")
        out += [f"*{split}, n = {b['n']}*", "", "| arm | Hit@5 | coverage@5 | coverage@20 |",
                "|---|---|---|---|"]
        for arm in ARMS:
            a = b["arms"][arm]
            out.append(f"| `{arm}` | {pct(a['hit@5'])} | {pct(a['chunk_cov@5'])} | "
                       f"{pct(a['chunk_cov@20'])} |")
        out.append("")
    out += [("**Multi-part queries: all-parts@5**: every part has a chunk in the top 5, next to "
            "Hit@5 (any part)."), ""]
    for split in SPLITS:
        b = block(r, f"{split}/all/multi_part")
        out += [f"*{split}, n = {b['n']}*", "", "| arm | Hit@5 | all-parts@5 |", "|---|---|---|"]
        for arm in ARMS:
            a = b["arms"][arm]
            out.append(f"| `{arm}` | {pct(a['hit@5'])} | {pct(a['all_parts@5'])} |")
        out.append("")
    out += [("**Large gold (gold spans cover 4+ chunks)**: Hit@5 reported separately, since a "
            "larger target is easier to hit."), ""]
    out += ["| split | n | " + " | ".join(f"`{a}`" for a in ARMS) + " |", "|---|---|" + "---|" * len(ARMS)]
    for split in SPLITS:
        b = block(r, f"{split}/all/gold4plus")
        b_rest = block(r, f"{split}/all/all")
        if b:
            out.append(f"| {split} (4+ chunks) | {b['n']} | " +
                       " | ".join(short(b["arms"][a]["hit@5"]) for a in ARMS) + " |")
        out.append(f"| {split} (all) | {b_rest['n']} | " +
                   " | ".join(short(b_rest["arms"][a]["hit@5"]) for a in ARMS) + " |")
    out.append("")

    out += ["## Unanswerable queries: top-1 signal for a later refusal threshold", "",
            ("Not scored for Hit/MRR. Median [p10, p90] of each arm's top-1 signal; `cosine` is the "
            "production embedding of the query against the top-1 chunk (one scale for every arm), "
            "`native` is the arm's own score (RRF for fused arms, BM25 score for bm25). A usable "
            "threshold needs the unanswerable distribution below the answerable one. The RRF "
            "score is bounded by rank arithmetic (a top-1 found by both lists scores "
            "0.5/61 + 0.5/61 = 0.016 with this configuration), so it carries no confidence "
            "information."), ""]
    rs = r["refusal_signal"]["all"]
    out += ["| arm | signal | answerable | unanswerable |", "|---|---|---|---|"]

    def dist(x):
        return "—" if not x else f"{x['median']:.3f} [{x['p10']:.3f}, {x['p90']:.3f}] (n={x['n']})"
    for arm in ARMS:
        for sig in ("cosine", "native"):
            if sig == "native" and arm.startswith("dense"):
                continue
            out.append(f"| `{arm}` | {sig} | {dist(rs[arm][f'answerable_{sig}'])} | "
                       f"{dist(rs[arm][f'unanswerable_{sig}'])} |")
    out.append("")

    out += ["## Typo effect (misspelled query vs its correctly spelled twin, same gold span)", "",
            "Rank of the first gold chunk; `—` = not retrieved (beyond the arm's list).", "",
            "| pair | " + " | ".join(f"`{a}`" for a in ARMS) + " |", "|---|" + "---|" * len(ARMS)]
    for pair, arms in r["typo_effect"].items():
        typo, correct = pair.split("|")

        def rk(x):
            return "—" if x is None else str(x)
        out.append(f"| `{typo}` / `{correct}` | " + " | ".join(
            f"{rk(arms[a]['typo_rank'])} / {rk(arms[a]['correct_rank'])}" for a in ARMS) + " |")
    out += ["", ("Cells are *misspelled / correct*. `production` returns 5 chunks, so its `—` means "
            "\"not in the 5 the generator sees\"; the other arms return 10-20.")]
    return "\n".join(out) + "\n"


def main() -> int:
    with open(RESULTS_PATH, encoding="utf-8") as handle:
        r = json.load(handle)
    with open(REPORT_PATH, "w", encoding="utf-8") as handle:
        handle.write(render(r))
    print(f"written: {REPORT_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
