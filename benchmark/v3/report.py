"""
Render benchmark/v3/RESULTS.md from benchmark/v3/results.json.

    python -m benchmark.v3.report

Generated, never hand-edited, so the report cannot drift from the data. The
Phase-0 baseline report is kept as RESULTS_phase0.md (from results_phase0.json).
"""

from __future__ import annotations

import json
import os
import statistics
import sys

V3_DIR = os.path.dirname(os.path.abspath(__file__))
RESULTS_PATH = os.path.join(V3_DIR, "results.json")
REPORT_PATH = os.path.join(V3_DIR, "RESULTS.md")

ARMS = ("production", "baseline_v3", "production_no_rerank", "dense_plain", "bm25")
REF = "baseline_v3"
SPLITS = ("dev", "holdout")
QTYPES = ("exact_identifier", "keyword", "misspelled", "paraphrase", "multi_hop",
          "list_all", "repo_identity")
HEAD_METRICS = ("hit@1", "hit@5", "mrr@5", "recall@20", "all_parts@5")


def pct(m: dict | None) -> str:
    if m is None:
        return "—"
    return f"{100 * m['mean']:.1f} [{100 * m['ci_low']:.1f}, {100 * m['ci_high']:.1f}]"


def short(m: dict | None) -> str:
    return "—" if m is None else f"{100 * m['mean']:.1f}"


def diff(d: dict) -> str:
    mark = " *" if d["excludes_zero"] else ""
    return f"{100 * d['diff']:+.1f} [{100 * d['ci_low']:+.1f}, {100 * d['ci_high']:+.1f}]{mark}"


def auroc(pos: list, neg: list) -> float | None:
    if not pos or not neg:
        return None
    wins = sum((a > u) + 0.5 * (a == u) for a in pos for u in neg)
    return wins / (len(pos) * len(neg))


def render(r: dict) -> str:
    agg = r["aggregates"]
    pq = r["per_query"]
    cfg, base = r["config"], r["baseline_v3_config"]
    fid = r.get("fidelity_default_hnsw") or {}
    out = ["# v3 retrieval results: Phase 1+2 against the frozen baseline", "",
           "Generated by `python -m benchmark.v3.report` from `results.json`. Do not edit by hand.",
           "The Phase-0 baseline report is [RESULTS_phase0.md](RESULTS_phase0.md).", ""]

    out += ["## Run", "",
            (f"- Frozen query set: manifest `{(r['manifest_sha256'] or '')[:12]}`, "
             f"split scored: **{r['scored_split']}**. Holdout was scored once, in this run."),
            (f"- `production` = `build_hybrid_retriever` as shipped: plain similarity top "
             f"{cfg['pool_k']} + BM25 top {cfg['pool_k']} (whole-identifier tokenizer), min-max "
             f"fusion alpha={cfg['fusion_alpha']}, `{cfg['reranker_model']}` over the top "
             f"{cfg['rerank_k']} (max_length {cfg['reranker_max_length']}, batch "
             f"{cfg['reranker_batch']}, budget {cfg['rerank_budget_s']}s), final {cfg['final_k']}, "
             f"README pin {'on' if cfg['surface_readme'] else 'off'}."),
            (f"- `baseline_v3` = the pipeline that shipped before, frozen in `baseline_v3.py`: MMR "
             f"k={base['mmr_k']}/fetch_k={base['mmr_fetch_k']}/lambda={base['mmr_lambda']} + BM25 "
             f"top {base['bm25_k']}, RRF k={base['rrf_smoothing']}, final {base['final_k']}, "
             "README pin on. Its top-5 lists reproduce the Phase-0 production results exactly."),
            f"- Production fallbacks in this run: {r['production_fallbacks']}.",
            (f"- Against a store with Chroma's default HNSW (what production uses), "
             f"{fid.get('identical')} of {fid.get('total')} production top-5 lists are identical "
             f"(differ: {', '.join(fid.get('differ', [])) or 'none'})."),
            (f"- Bootstrap: {r['bootstrap']['resamples']} paired resamples, seed "
             f"{r['bootstrap']['seed']}, 95% percentile intervals. `*` marks a paired difference "
             "whose interval excludes 0. Differences are arm minus `baseline_v3`."),
            "- Libraries: " + ", ".join(f"{k} {v}" for k, v in r["libraries"].items()), ""]

    out += ["## Production against the baseline, per split and domain", "",
            ("Paired differences, production minus baseline_v3, in points. Hit@k / MRR@5 measure the "
             "5 chunks the generator sees; Recall@20 is the candidate pool's top 20 (for "
             "production, what the reranker scores)."), ""]
    for split in SPLITS:
        out += [f"### {split}", "",
                "| domain | n | metric | baseline_v3 | production | difference |",
                "|---|---|---|---|---|---|"]
        for dom in ("all", "code", "docs"):
            b = agg[f"{split}/{dom}/all"]
            for m in HEAD_METRICS:
                out.append(f"| {dom} | {b['n']} | {m} | {pct(b['arms'][REF][m])} | "
                           f"{pct(b['arms']['production'][m])} | "
                           f"{diff(b['vs_baseline']['production'][m])} |")
        out.append("")

    out += ["## All arms (all answerable queries)", ""]
    for split in SPLITS:
        b = agg[f"{split}/all/all"]
        out += [f"### {split} (n = {b['n']})", "",
                "| arm | Hit@1 | Hit@5 | MRR@5 | Recall@20 | all-parts@5 |", "|---|---|---|---|---|---|"]
        for arm in ARMS:
            a = b["arms"][arm]
            out.append(f"| `{arm}` | " + " | ".join(pct(a[m]) for m in HEAD_METRICS) + " |")
        out += ["", "| arm minus baseline_v3 | Hit@1 | Hit@5 | MRR@5 | Recall@20 | all-parts@5 |",
                "|---|---|---|---|---|---|"]
        for arm in ARMS:
            if arm != REF:
                d = b["vs_baseline"][arm]
                out.append(f"| `{arm}` | " + " | ".join(diff(d[m]) for m in HEAD_METRICS) + " |")
        out.append("")

    out += ["## By query type (Hit@1 / Hit@5, %)", "",
            "Small cells: read the n before the number. Intervals are in `results.json`.", ""]
    for split in SPLITS:
        out += [f"### {split}", "", "| qtype | n | baseline_v3 | production | production_no_rerank |",
                "|---|---|---|---|---|"]
        for qt in QTYPES:
            b = agg.get(f"{split}/all/{qt}")
            if b:
                cells = [f"{short(b['arms'][a]['hit@1'])} / {short(b['arms'][a]['hit@5'])}"
                         for a in (REF, "production", "production_no_rerank")]
                out.append(f"| {qt} | {b['n']} | " + " | ".join(cells) + " |")
        out.append("")

    out += ["## Coverage metrics", "",
            "**list_all: chunk coverage**, the share of gold-span chunks retrieved.", "",
            "| split | n | baseline_v3 @5 | production @5 | baseline_v3 @20 | production @20 |",
            "|---|---|---|---|---|---|"]
    for split in SPLITS:
        b = agg[f"{split}/all/list_all"]
        out.append(f"| {split} | {b['n']} | {pct(b['arms'][REF]['chunk_cov@5'])} | "
                   f"{pct(b['arms']['production']['chunk_cov@5'])} | "
                   f"{pct(b['arms'][REF]['chunk_cov@20'])} | "
                   f"{pct(b['arms']['production']['chunk_cov@20'])} |")
    out += ["", "**Multi-part queries**: Hit@5 (any part) and all-parts@5 (every part in the top 5).", "",
            "| split | n | baseline_v3 Hit@5 | production Hit@5 | baseline_v3 all-parts@5 | production all-parts@5 |",
            "|---|---|---|---|---|---|"]
    for split in SPLITS:
        b = agg[f"{split}/all/multi_part"]
        out.append(f"| {split} | {b['n']} | {pct(b['arms'][REF]['hit@5'])} | "
                   f"{pct(b['arms']['production']['hit@5'])} | {pct(b['arms'][REF]['all_parts@5'])} | "
                   f"{pct(b['arms']['production']['all_parts@5'])} |")
    out += ["", "**Gold spans covering 4+ chunks** (an easier target), Hit@5.", "",
            "| split | n | baseline_v3 | production |", "|---|---|---|---|"]
    for split in SPLITS:
        b = agg.get(f"{split}/all/gold4plus")
        if b:
            out.append(f"| {split} | {b['n']} | {pct(b['arms'][REF]['hit@5'])} | "
                       f"{pct(b['arms']['production']['hit@5'])} |")
    out.append("")

    out += ["## Refusal signal (not wired in)", "",
            ("AUROC of each top-1 signal for separating answerable from unanswerable queries "
             "(1.0 = perfect, 0.5 = chance). `production` native = the reranker's top-1 score; "
             "cosine = production embedding of the query against the top-1 chunk."), "",
            "| split | answerable / unanswerable | reranker score | production cosine | baseline_v3 RRF score |",
            "|---|---|---|---|---|"]
    for split in SPLITS:
        rows = [q for q in pq.values() if q["split"] == split]

        def sig(arm, kind, want, rows=rows):
            return [q["top1"][arm][kind] for q in rows
                    if (q["qtype"] == "unanswerable") == want and q["top1"][arm][kind] is not None]
        n_a = sum(1 for q in rows if q["qtype"] != "unanswerable")
        n_u = len(rows) - n_a
        cells = []
        for arm, kind in (("production", "native"), ("production", "cosine"), (REF, "native")):
            a = auroc(sig(arm, kind, False), sig(arm, kind, True))
            cells.append("—" if a is None else f"{a:.3f}")
        out.append(f"| {split} | {n_a} / {n_u} | " + " | ".join(cells) + " |")
    thr = -7.5
    out += ["", f"At the suggested threshold of {thr} on the reranker score:", ""]
    for split in SPLITS:
        rows = [q for q in pq.values() if q["split"] == split and q["top1"]["production"]["native"] is not None]
        a = [q for q in rows if q["qtype"] != "unanswerable"]
        u = [q for q in rows if q["qtype"] == "unanswerable"]
        kept = sum(q["top1"]["production"]["native"] >= thr for q in a)
        flagged = sum(q["top1"]["production"]["native"] < thr for q in u)
        out.append(f"- {split}: keeps {kept}/{len(a)} answerable, flags {flagged}/{len(u)} unanswerable.")
    out.append("")

    ms = [q["production_log"]["rerank_ms"] for q in pq.values() if q["production_log"]["rerank_ms"] is not None]
    if ms:
        out += ["## Rerank time in this run", "",
                (f"Median {statistics.median(ms):.0f} ms, max {max(ms)} ms over {len(ms)} queries, measured "
                 "in the evaluation process (multi-threaded). On one thread, as on rag-qa's single vCPU, "
                 "20 pairs measured p50 1.04 s / p95 1.28 s; see docs/DECISIONS.md."), ""]

    out += ["## Typo effect (misspelled query vs its correctly spelled twin)", "",
            "Rank of the first gold chunk; `—` = not in the arm's list (production returns 5).", "",
            "| pair | baseline_v3 | production |", "|---|---|---|"]

    def rk(x):
        return "—" if x is None else str(x)
    for pair, arms in r["typo_effect"].items():
        typo, correct = pair.split("|")
        out.append(f"| `{typo}` / `{correct}` | {rk(arms[REF]['typo_rank'])} / {rk(arms[REF]['correct_rank'])} | "
                   f"{rk(arms['production']['typo_rank'])} / {rk(arms['production']['correct_rank'])} |")
    out += ["", "Cells are *misspelled / correct*."]
    return "\n".join(out) + "\n"


def main() -> int:
    with open(RESULTS_PATH, encoding="utf-8") as handle:
        r = json.load(handle)
    with open(REPORT_PATH, "w", encoding="utf-8") as handle:
        handle.write(render(r))
    print(f"written: {REPORT_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
